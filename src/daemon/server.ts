class BadRequest extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'BadRequest';
  }
}

/** A request's path without its query, which can carry a user ID (the upload route's `user=`): what a log record names. */
function pathOf(req: IncomingMessage): string {
  return present((req.url ?? '').split('?')[0], 'request path');
}

export function createDaemonServer(props: DaemonServerProps): Server {
  // requireHostHeader off: Node would answer a request without Host with its own 400, unlogged; the guard
  // refuses it like any foreign Host (403, http.refused). The option exists since Node 20 (the integration
  // test 'answers 403 to a foreign Host' proves it on the Node that runs the gate); @types/node 22.13 lacks it.
  return createServer({ requireHostHeader: false } as ServerOptions, (req, res) => {
    const ended = props.activity();
    res.once('close', () => {
      ended();
    });
    route(props, req, res).catch((error: unknown) => {
      if (
        error instanceof BadRequest ||
        error instanceof AgentRequestInvalid ||
        error instanceof ChannelNameInvalid ||
        error instanceof UserIdInvalid ||
        error instanceof ChannelRequestInvalid ||
        error instanceof TraceRequestInvalid
      ) {
        // A call's refusal names its reason, which the agent acts on (docs/plans/agent-calls.md R2, R5, R6).
        const body =
          error instanceof CallRefused ? { error: error.message, reason: error.reason } : { error: error.message };
        sendJson(res, error instanceof ChannelRequestInvalid ? 409 : 400, body);
        return;
      }
      props.logger.error('http.handler_failed', { method: req.method, url: pathOf(req), error });
      if (res.headersSent) res.destroy(error as Error);
      else sendJson(res, 500, { error: 'internal error; see the daemon log' });
    });
  });
}

const REFUSED: Readonly<Record<RefusalReason, readonly [status: number, message: string]>> = {
  host_forbidden: [403, 'forbidden Host header'],
  origin_forbidden: [403, 'forbidden Origin header'],
  credential_missing: [401, 'missing control credential; the CLI reads it from daemon.json'],
  credential_invalid: [401, 'invalid control credential'],
  token_missing: [401, 'missing or unknown agent token'],
  token_invalid: [401, 'missing or unknown agent token'],
};

function apiFamily(path: string): ApiFamily {
  if (path === '/v1' || path.startsWith('/v1/')) return 'v1';
  if (path === '/agent' || path.startsWith('/agent/')) return 'agent';
  return 'other';
}

/**
 * Refuses a request that fails the guard, logging it, and answers why; returns
 * undefined when it passes. In order: `Host` must be exactly the daemon's
 * loopback address (or, on `/agent/`, the containers' name for the host) with
 * its port; an `Origin`, when sent, must be the daemon's own; then `/v1/`
 * needs the control credential and `/agent/` a live agent token, each only as
 * `Authorization: Bearer`. Nothing else about the request is read first.
 */
function guard(props: DaemonServerProps, req: IncomingMessage, api: ApiFamily): RefusalReason | undefined {
  const port = props.port();
  const local = [`127.0.0.1:${port.toString()}`, `localhost:${port.toString()}`];
  const hosts = api === 'agent' ? [...local, `${props.agentHostAddress}:${port.toString()}`] : local;
  const host = req.headers.host;
  if (host === undefined || !hosts.includes(host)) return 'host_forbidden';
  const origin = req.headers.origin;
  if (
    origin !== undefined &&
    origin !== `http://127.0.0.1:${port.toString()}` &&
    origin !== `http://localhost:${port.toString()}`
  )
    return 'origin_forbidden';
  if (api === 'v1') {
    const presented = bearer(req);
    if (presented === undefined) return 'credential_missing';
    if (!sameSecret(presented, props.credential)) return 'credential_invalid';
  }
  if (api === 'agent') {
    const token = bearer(req);
    if (token === undefined) return 'token_missing';
    // A Map lookup hashes the presented string, so its timing does not reveal how much of a token matched.
    if (!props.supervisor.isAgentToken(token)) return 'token_invalid';
  }
  return undefined;
}

/** Constant-time comparison; a length mismatch is a mismatch. */
function sameSecret(presented: string, expected: string): boolean {
  const a = Buffer.from(presented, 'utf8');
  const b = Buffer.from(expected, 'utf8');
  return a.length === b.length && timingSafeEqual(a, b);
}

async function route(props: DaemonServerProps, req: IncomingMessage, res: ServerResponse): Promise<void> {
  // The scheme is never used (only .pathname and .searchParams are read below): https avoids sonarjs flagging a
  // literal http:// it would never connect over, as a plain parsing base for the path Node already received.
  const url = new URL(req.url ?? '/', 'https://daemon');
  // String(), not `?? ''`: req.method is undefined only in cases Node itself never produces, and this must render
  // exactly as the old implicit coercion did ("undefined ..."), matching no route, so a request like that still
  // falls through to the 404 that names it, rather than silently becoming " ..." and matching nothing for a
  // different-looking reason.
  const key = `${String(req.method)} ${url.pathname}`;

  const api = apiFamily(url.pathname);
  const refused = guard(props, req, api);
  if (refused !== undefined) {
    refuse(props, req, res, url, api, refused);
    return;
  }

  if (api === 'other') {
    servePortalFile(props, req, res, url, key);
    return;
  }

  if (api === 'v1' && props.stopping()) {
    // reason: what tells the CLI a stopping daemon from an absent one (debt-paydown R15).
    sendJson(res, 503, { error: 'the daemon is stopping', reason: 'stopping' });
    return;
  }

  // extension-modules R12 (b): a pending approval request, and its approval.
  if (url.pathname.startsWith(`${Routes.approvals}/`) && (req.method === 'GET' || req.method === 'POST')) {
    await approvalRoute(props, req, res, url.pathname.slice(Routes.approvals.length + 1));
    return;
  }

  if (req.method === 'GET' && url.pathname.startsWith(`${Routes.channelFiles}/`)) {
    await download(props, res, url.pathname.slice(Routes.channelFiles.length + 1));
    return;
  }

  // Every route below whose key is an exact "<method> <path>" match is mutually exclusive by construction (each
  // Routes value names a distinct path), so one lookup replaces what was a chain of ~20 sibling `if`s — itself
  // already over sonarjs/cognitive-complexity's bound before any nesting inside them. Each handler's body is
  // unchanged from the block it was extracted from.
  const handler = V1_ROUTES[key];
  if (handler !== undefined) {
    await handler(props, req, res, url);
    return;
  }

  if (api === 'agent' && (await routeAgent(props, req, res, url, key))) return;

  sendJson(res, 404, { error: `no route for ${key}` });
}

/** Logs a refusal from guard() and answers why, matching REFUSED. Extracted from route() to keep it within bound. */
function refuse(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
  url: URL,
  api: ApiFamily,
  refused: RefusalReason,
): void {
  props.refusals.record({
    reason: refused,
    api,
    method: req.method ?? '',
    // Never the credential, even if a caller put it in the path (redacted before the cut, so no part of it
    // survives), and bounded.
    path: url.pathname.replaceAll(props.credential, '<credential>').slice(0, 200),
  });
  const [status, error] = REFUSED[refused];
  // A portal path's refusal carries the portal's headers too: every response of a portal path does (R13).
  const headers = api === 'other' ? portalHeaders('application/json') : { 'content-type': 'application/json' };
  res.writeHead(status, { ...headers, ...(status === 401 ? { 'www-authenticate': 'Bearer' } : {}) });
  res.end(JSON.stringify({ error }));
}

/** The portal's page (R2, R13): only allow-listed files, as read at start, each with the policy; anything else 404. */
function servePortalFile(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
  url: URL,
  key: string,
): void {
  const file = req.method === 'GET' ? props.portal.file(url.pathname) : undefined;
  if (file === undefined) {
    res.writeHead(404, portalHeaders('application/json'));
    res.end(JSON.stringify({ error: `no route for ${key}` }));
    return;
  }
  res.writeHead(200, { ...portalHeaders(file.contentType), 'content-length': String(file.body.byteLength) });
  res.end(file.body);
}

