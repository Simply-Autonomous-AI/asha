/** `POST /agent/v1/channel/messages` (patterns-phase-3 R23, R24; agent-files R12). */
async function handleAgentMessages(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
  token: string,
): Promise<void> {
  const body = closedBody(await readJson(req), ['conversation', 'kind', 'text', 'to', 'files', 'asks']);
  const kind = body['kind'];
  if (kind !== 'internal' && kind !== 'output' && kind !== 'status') {
    throw new BadRequest('kind must be "internal", "output" or "status"');
  }
  const to = optionalString(body, 'to');
  const conversation = optionalString(body, 'conversation');
  if (conversation === undefined && kind !== 'status') throw new BadRequest('conversation must be a non-empty string');
  // A post in a conversation names the agent's post span, in the conversation's trace (R2a).
  const parent = conversation === undefined ? undefined : traceparent(req, traceIdFor(conversation));
  // ask_user (patterns-phase-3 R23, R24): only `true`, on an output, which takes no "to" and no files.
  if (
    body['asks'] !== undefined &&
    (body['asks'] !== true || kind !== 'output' || to !== undefined || body['files'] !== undefined)
  ) {
    throw new BadRequest('asks must be true, on an output with neither "to" nor files');
  }
  if (body['files'] !== undefined) {
    await handleAgentMessagesWithFiles(props, res, token, body, kind, to, conversation, parent);
    return;
  }
  const message = props.supervisor.post(
    token,
    {
      kind,
      text: nonEmptyString(body, 'text'),
      ...(conversation === undefined ? {} : { conversation }),
      ...(to === undefined ? {} : { to }),
      ...(body['asks'] === true ? { asks: true as const } : {}),
    },
    parent?.spanId,
  );
  sendJson(res, 200, { message });
}

/**
 * reply_with_files (agent-files R12): an output's files, copied out and checked; a refusal is 409, nothing posted.
 * Extracted from handleAgentMessages to keep its cognitive complexity within bound.
 */
async function handleAgentMessagesWithFiles(
  props: DaemonServerProps,
  res: ServerResponse,
  token: string,
  body: { readonly [key: string]: unknown },
  kind: 'internal' | 'output' | 'status',
  to: string | undefined,
  conversation: string | undefined,
  parent: TraceParent | undefined,
): Promise<void> {
  const files = body['files'];
  if (kind !== 'output' || to !== undefined) throw new BadRequest('files come only on an output, which takes no "to"');
  if (!Array.isArray(files) || !files.every((f) => typeof f === 'string' && f.length > 0 && f.length <= 4_096))
    throw new BadRequest('files must be a list of paths in /channel');
  const posted = await props.supervisor.postWithFiles(
    token,
    {
      conversation: present(conversation, 'conversation (kind=output)'),
      text: nonEmptyString(body, 'text'),
      files: files as string[],
    },
    present(parent, 'traceparent (kind=output)').spanId,
  );
  if (!posted.ok) {
    sendJson(res, 409, {
      error: `file refused: ${posted.file}: ${posted.rule}`,
      reason: 'file_refused',
      file: posted.file,
      rule: posted.rule,
    });
    return;
  }
  sendJson(res, 200, { message: posted.message });
}

