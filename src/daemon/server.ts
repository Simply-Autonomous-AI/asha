/** `POST /v1/channel/files`: a message's attachments, one upload (agent-files R3a). */
async function handleChannelFilesUpload(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
  url: URL,
): Promise<void> {
  // A raw body, read as a stream and never passed to readJson (R3a): the manifest's line, then the files' bytes.
  const channel = url.searchParams.get('channel') ?? '';
  const user = url.searchParams.get('user') ?? '';
  if (!NAME_PATTERN.test(channel)) throw new BadRequest(`channel must be a channel name (${NAME_PATTERN.toString()})`);
  const problem = userIdProblem(user, { isDefault: false });
  if (problem !== undefined) throw new BadRequest(`user: ${problem}`);
  if ((req.headers['content-type'] ?? '') !== 'application/octet-stream')
    throw new BadRequest('an upload is sent as application/octet-stream');
  const result = await props.files.upload({ channel, user, body: req });
  if (result.ok) {
    sendJson(res, 200, result.answer);
    return;
  }
  sendJson(res, result.status, { error: result.detail, reason: result.reason });
  // A refusal met after the body began to be read: the rest is read and discarded, bounded, so a browser — which
  // reads no answer before it has sent its whole body — reads this one (docs/plans/portal.md R8b); any end but the
  // body's own closes the connection.
  if (result.drain !== undefined) {
    const socket = req.socket;
    let onClose: (() => void) | undefined;
    const closed = socket.destroyed
      ? Promise.resolve()
      : new Promise<void>((resolve) => {
          onClose = () => {
            resolve();
          };
          socket.once('close', onClose);
        });
    const outcome = await result.drain(closed);
    // A kept-alive connection may carry more uploads: this drain's listener goes with it.
    if (onClose !== undefined) socket.off('close', onClose);
    if (outcome !== 'ended') socket.destroy();
  }
}

