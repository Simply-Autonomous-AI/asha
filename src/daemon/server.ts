/** `GET /v1/blackboard?channel=[&since=]` (patterns-phase-4 R1, R2). */
function handleBlackboardRead(props: DaemonServerProps, _req: IncomingMessage, res: ServerResponse, url: URL): void {
  // patterns-phase-4 R1, R2: one channel's board, read as the agent route reads it; no channel or board made, nothing logged.
  const name = url.searchParams.get('channel');
  const since = url.searchParams.get('since');
  if (name === null || !NAME_PATTERN.test(name)) {
    sendJson(res, 400, {
      error: 'invalid_arguments',
      detail: `channel must be a channel name (${NAME_PATTERN.toString()})`,
    });
    return;
  }
  if (since !== null && !BLACKBOARD_SINCE.test(since)) {
    sendJson(res, 400, { error: 'invalid_arguments', detail: 'since must be a whole number from 0 to 999999999' });
    return;
  }
  const channel = props.channels.existing(name);
  if (channel === undefined) {
    sendJson(res, 404, { error: `no channel ${name} on this daemon`, reason: 'unknown_channel' });
    return;
  }
  const body: BlackboardReadResponse = props.supervisor.channelBlackboard(channel, since === null ? 0 : Number(since));
  sendJson(res, 200, body);
}

