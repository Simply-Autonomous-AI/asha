/** `POST /v1/stop` (R14): answered first; the stop begins once the answer is on its way, so the page reads it before the server closes. */
function handleStop(props: DaemonServerProps, _req: IncomingMessage, res: ServerResponse): void {
  const body: StopResponse = { pid: props.pid };
  // A client gone before its answer was sent gets no 202 and begins no stop: it sees the failure and may ask again.
  res.once('finish', () => {
    props.requestStop();
  });
  sendJson(res, 202, body);
}

/** `POST /v1/channel/stop`'s validation, before channelStop()'s stream (R1). */
async function handleChannelStopRoute(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
): Promise<void> {
  const body = closedBody(await readJson(req), ['channel', 'source']);
  const name = nonEmptyString(body, 'channel');
  if (!NAME_PATTERN.test(name)) throw new BadRequest(`channel must be a channel name (${NAME_PATTERN.toString()})`);
  const source = body['source'];
  if (source !== 'portal' && source !== 'cli') throw new BadRequest('source must be portal or cli');
  // R1: a channel with no agent, online or launching, has nothing to stop.
  if (!props.supervisor.hasAgentsOn(name)) {
    sendJson(res, 404, { error: `no agent is on channel "${name}"`, reason: 'unknown_channel' });
    return;
  }
  await channelStop(props, res, name, source);
}

