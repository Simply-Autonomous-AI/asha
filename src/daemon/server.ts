/**
 * `POST /v1/portal/errors` (docs/plans/portal.md R6): the page's failure report, exactly `{reason, detail}`. 204 and
 * logged, bounded; 400 for any other body; 413 for a body over PORTAL_ERROR_MAX_BYTES, read no further than one byte
 * past it. Neither refusal is logged as a client error.
 */
async function portalError(props: DaemonServerProps, req: IncomingMessage, res: ServerResponse): Promise<void> {
  const chunks: Buffer[] = [];
  let size = 0;
  for await (const chunk of req) {
    size += (chunk as Buffer).byteLength;
    if (size > PORTAL_ERROR_MAX_BYTES) {
      res.writeHead(413, { 'content-type': 'application/json', connection: 'close' });
      res.end(JSON.stringify({ error: `a report is at most ${PORTAL_ERROR_MAX_BYTES.toString()} bytes` }));
      return;
    }
    chunks.push(chunk as Buffer);
  }
  let body: unknown;
  try {
    body = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  } catch {
    throw new BadRequest('body is not valid JSON');
  }
  const report = parsePortalError(body);
  if (typeof report === 'string') throw new BadRequest(report);
  props.portalErrors.record(report);
  res.writeHead(204);
  res.end();
}

/**
 * The request's `traceparent`, which a chat, embed or conversation post must
 * carry; with `traceId`, it must also be in that trace. Anything else is a 400.
 */
function traceparent(req: IncomingMessage, traceId?: string): TraceParent {
  const header = req.headers[TRACEPARENT_HEADER];
  const parent = parseTraceparent(typeof header === 'string' ? header : undefined);
  if (parent === undefined)
    throw new BadRequest(`${TRACEPARENT_HEADER} must be 00-<32 hex>-<16 hex>-01, naming the caller's span`);
  if (traceId !== undefined && parent.traceId !== traceId)
    throw new BadRequest(`${TRACEPARENT_HEADER} must be in the conversation's trace, ${traceId}`);
  return parent;
}

/** An OTLP/HTTP JSON body: application/json only (protobuf is not accepted). */
async function readTraces(req: IncomingMessage): Promise<unknown> {
  const type = req.headers['content-type'] ?? '';
  if (!/^application\/json(;|$)/.test(type))
    throw new BadRequest('spans must be sent as OTLP/HTTP JSON (content-type: application/json)');
  return readJson(req);
}

/** The error event every control stream can end with. */
export type StreamError = { readonly type: 'error'; readonly reason: ConversationErrorReason; readonly detail: string };

/** A control route's open SSE stream (docs/plans/model-streaming.md R5, R6). */
export interface ControlStream<E extends { readonly type: string }> {
  /**
   * Writes one event; nothing once the stream has ended. A property of function type, not a method signature, so
   * passing it detached (`channel.watch(id, stream.write)`) is not an unbound-method risk: it closes over nothing
   * named `this`.
   */
  readonly write: (event: E) => void;
  /** Ends the stream (its heartbeat stops). */
  end(): void;
  /** Whether it has ended: the reader hung up, fell behind, or the route ended it. */
  ended(): boolean;
}

/**
 * Answers a control route with an SSE stream: `text/event-stream`, a `: heartbeat` comment every heartbeatMs, and
 * each event as `event:` and `data:` lines. A reader that falls more than SSE_MAX_UNWRITTEN_BYTES behind gets one
 * `error` `slow_reader` event after what is buffered, and its stream alone ends (R6): the writer, a model call
 * among them, never waits on it. `onEnd` runs once, when the stream ends for any reason.
 */
function controlStream<E extends { readonly type: string }>(
  props: DaemonServerProps,
  res: ServerResponse,
  route: { readonly route: string; readonly channel: string },
  onEnd: () => void,
): ControlStream<E | StreamError> {
  res.writeHead(200, { 'content-type': SSE_CONTENT_TYPE, 'cache-control': 'no-store' });
  let ended = false;
  const finish = (): void => {
    if (ended) return;
    ended = true;
    clearInterval(heartbeat);
    onEnd();
  };
  const send = (text: string): void => {
    if (ended || res.destroyed || res.writableEnded) return;
    res.write(text);
    if (res.writableLength <= SSE_MAX_UNWRITTEN_BYTES) return;
    const unwritten = res.writableLength;
    props.logger.error('stream.slow_reader', {
      ...route,
      unwrittenBytes: unwritten,
      error: new Error(
        `the reader of ${route.route} fell ${unwritten.toString()} bytes behind, over ${SSE_MAX_UNWRITTEN_BYTES.toString()}; its stream was ended`,
      ),
    });
    const slow: StreamError = {
      type: 'error',
      reason: 'slow_reader',
      detail: `the stream fell more than ${SSE_MAX_UNWRITTEN_BYTES.toString()} bytes behind its reader, and was ended`,
    };
    res.end(sseEvent(slow));
    finish();
  };
  const heartbeat = setInterval(() => {
    send(SSE_HEARTBEAT);
  }, props.heartbeatMs);
  res.once('close', finish);
  return {
    write: (event) => {
      send(sseEvent(event));
    },
    end: () => {
      if (!res.writableEnded) res.end();
      finish();
    },
    ended: () => ended || res.destroyed,
  };
}

/**
 * `POST /v1/channel/stop`'s stream (docs/plans/portal-demo-stop.md R1–R3): `stopping` with the agents on the channel,
 * one `agent_stopped` as each is gone, then each model server stopped because no agent needs it, then `stopped`; a
 * failure of either step is one `error` event, already logged where it happened. A stop begun goes on if the reader
 * hangs up: its agents are drained, and its outcome logged, whether or not anyone reads it.
 */
async function channelStop(
  props: DaemonServerProps,
  res: ServerResponse,
  name: string,
  source: 'portal' | 'cli',
): Promise<void> {
  const stream = controlStream<ChannelStopEvent>(
    props,
    res,
    { route: Routes.channelStop, channel: name },
    () => undefined,
  );
  try {
    stream.write({ type: 'stopping', channel: name, handles: props.supervisor.agentsOn(name) });
    const handles = await props.supervisor.stopChannel(name, source, (handle) => {
      stream.write({ type: 'agent_stopped', handle });
    });
    let modelServers: string[];
    try {
      modelServers = await props.stopIdleModels();
    } catch (error) {
      props.logger.error('model_server.stop_idle_failed', { channel: name, error });
      stream.write({
        type: 'error',
        reason: 'channel_stop_failed',
        detail: `its agents stopped, but the idle model servers' stop failed: ${error instanceof Error ? error.message : String(error)}`,
      });
      return;
    }
    for (const model of modelServers) stream.write({ type: 'model_server_stopped', model });
    stream.write({ type: 'stopped', channel: name, handles, modelServers });
  } catch (error) {
    if (!(error instanceof ChannelStopFailed)) throw error;
    stream.write({ type: 'error', reason: 'channel_stop_failed', detail: error.message });
  } finally {
    stream.end();
  }
}

