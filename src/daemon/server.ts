/** `POST /agent/v1/agents` (patterns-phase-3 R30): an agent launches a recipe its grant names, for the delivery it holds. */
async function handleAgentLaunch(
  props: DaemonServerProps,
  req: IncomingMessage,
  res: ServerResponse,
  token: string,
): Promise<void> {
  const body = closedBody(await readJson(req), ['delivery', 'recipe']);
  const request = { delivery: nonEmptyString(body, 'delivery'), recipe: nonEmptyString(body, 'recipe') };
  if (props.stopping()) {
    sendJson(res, 503, { error: 'the daemon is stopping', reason: 'stopping' });
    return;
  }
  // The caller's request closing before the answer (its SDK's bound passed) abandons the launch.
  const abandon = new AbortController();
  const closed = (): void => {
    if (!res.writableEnded) abandon.abort();
  };
  res.once('close', closed);
  const outcome = await props.supervisor.launchFor(token, request, abandon.signal);
  res.off('close', closed);
  if (outcome.ok) {
    const answer: AgentLaunchResponse = { handle: outcome.handle };
    sendJson(res, 200, answer);
  } else if (outcome.reason === 'stopping') sendJson(res, 503, { error: outcome.detail, reason: 'stopping' });
  // Its caller is gone: there is nobody to answer.
  else if (outcome.reason !== 'abandoned')
    sendJson(res, 409, { error: `${outcome.reason}: ${outcome.detail}`, reason: outcome.reason });
}

