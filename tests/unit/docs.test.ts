// The documentation guard (PRINCIPLES §17, §19; AGENTS.md §4). The Markdown
// under docs/ is the source and each .html beside it is its committed render
// (tools/docs/render.mts): this re-renders every source and fails on a stale or
// sourceless page. The rendered pages are then checked as a reader gets them:
// every page is listed directly by docs/index.html or by its own section's
// index.html, links the shared stylesheet, loads nothing from the network, has
// unique ids, and every relative link resolves — to a file that exists (never a
// .md source) and, for a #fragment into a page, to an id that page defines. The
// root Markdown files' links into docs/ resolve too, fragments included. No page
// outside docs/plans/, nor the README or the guidance, links into a path the
// public export leaves out (tools/oss/manifest.json; docs/plans/oss-release.md
// R13, R37): such a page cites a plan as code, and a `planned` badge outside
// docs/plans/ is a span naming its plan. The plans' own checks — each status and
// its index row, the counts, the debt lines — are docs-plans.test.ts's, which
// stays with the plans in the internal repository. Parsed with regexes on purpose: the
// pages are simple generated HTML, and a parser dependency would buy nothing
// here (PRINCIPLES §7).

