/** A closed-open version interval, `[from, to)`: `to` is `Infinity` for an unbounded `>=` clause. */
interface VersionInterval {
  readonly from: number;
  readonly to: number;
}

/** `major.minor.patch` as one comparable integer (Node's own components never reach 1,000). */
const versionNumber = (major: number, minor: number, patch: number): number =>
  major * 1_000_000 + minor * 1_000 + patch;

/** One `||`-separated clause of an `engines.node` range — `^X.Y.Z` or `>=X[.Y[.Z]]` — as the interval it admits. */
function parseEngineClause(clause: string): VersionInterval {
  const caret = /^\^(\d+)\.(\d+)\.(\d+)$/.exec(clause);
  if (caret !== null) {
    const major = Number(present(caret[1], "the caret clause's major version"));
    const minor = Number(present(caret[2], "the caret clause's minor version"));
    const patch = Number(present(caret[3], "the caret clause's patch version"));
    return { from: versionNumber(major, minor, patch), to: versionNumber(major + 1, 0, 0) };
  }
  const atLeast = /^>=(\d+)(?:\.(\d+))?(?:\.(\d+))?$/.exec(clause);
  if (atLeast !== null) {
    const major = Number(present(atLeast[1], "the >= clause's major version"));
    const minor = Number(atLeast[2] ?? '0');
    const patch = Number(atLeast[3] ?? '0');
    return { from: versionNumber(major, minor, patch), to: Infinity };
  }
  throw new Error(`an engines.node clause this guard does not read: ${JSON.stringify(clause)}`);
}

/** `range` (one or more `||`-separated clauses) as the versions it admits. */
const parseEngineRange = (range: string): VersionInterval[] =>
  range.split('||').map((c) => parseEngineClause(c.trim()));

/** Every version both `a` and `b` admit: each pair of their intervals, trimmed to their overlap, lowest first. */
function intersectEngineRanges(a: readonly VersionInterval[], b: readonly VersionInterval[]): VersionInterval[] {
  const out: VersionInterval[] = [];
  for (const x of a)
    for (const y of b) {
      const from = Math.max(x.from, y.from);
      const to = Math.min(x.to, y.to);
      if (from < to) out.push({ from, to });
    }
  return out.sort((p, q) => p.from - q.from);
}

/** One admitted interval, written the way `engines.node` writes a clause: `^major.minor.patch` when it ends at the next major, `>=major.minor.patch` when it is unbounded. */
function formatEngineInterval(i: VersionInterval): string {
  const major = Math.floor(i.from / 1_000_000);
  const minor = Math.floor((i.from % 1_000_000) / 1_000);
  const patch = i.from % 1_000;
  if (i.to === versionNumber(major + 1, 0, 0)) return `^${String(major)}.${String(minor)}.${String(patch)}`;
  if (i.to === Infinity) return `>=${String(major)}.${String(minor)}.${String(patch)}`;
  throw new Error(`an admitted interval this guard cannot write back as one clause: ${JSON.stringify(i)}`);
}

