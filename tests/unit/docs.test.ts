const isRelative = (url: string): boolean => !isNetwork(url) && !/^[a-z][a-z0-9+.-]*:/i.test(url.trim());

/** Where a relative link points: the file (without #fragment or ?query) and the fragment, if any. */
function target(page: string, url: string): { readonly file: string; readonly fragment: string } {
  const [pathAndQuery, fragment = ''] = url.split('#', 2) as [string, string?];
  const path = present(pathAndQuery.split('?')[0], 'the path before any ?query');
  return {
    file: path === '' ? page : resolve(dirname(page), decodeURIComponent(path)),
    fragment: decodeURIComponent(fragment),
  };
}

/**
 * A page's ids, parsed once per page: the link check asks for them once per #fragment link, and a large page (a
 * plan) links to its own fragments hundreds of times — re-parsing it each time made the check quadratic and slow
 * enough to time out under a loaded full run (2026-09-29).
 */
const idCache = new Map<string, Set<string>>();
function ids(page: string): Set<string> {
  let found = idCache.get(page);
  if (found === undefined) {
    found = new Set(tags(readFileSync(page, 'utf8')).flatMap((t) => (t.attrs.id === undefined ? [] : [t.attrs.id])));
    idCache.set(page, found);
  }
  return found;
}

/** `href` loads a resource on these tags; on `<a>` it is a link the reader follows, not a load. */
const LOADS_HREF = new Set(['link', 'image', 'use', 'feimage', 'script']);

/** Every `src`/`data`/`poster`/`xlink:href` (and `href`, on the tags that load it) and `srcset`/`imagesrcset` of one tag that names a network URL. */
function tagRemoteProblems(page: string, t: Tag): string[] {
  const problems: string[] = [];
  for (const attr of ['src', 'data', 'poster', 'xlink:href', ...(LOADS_HREF.has(t.tag) ? ['href'] : [])]) {
    const url = t.attrs[attr];
    if (url !== undefined && isNetwork(url)) problems.push(`${name(page)}: <${t.tag} ${attr}="${url}">`);
  }
  for (const attr of ['srcset', 'imagesrcset']) {
    const set = t.attrs[attr];
    if (set !== undefined && set.split(',').some((candidate) => isNetwork(candidate)))
      problems.push(`${name(page)}: <${t.tag} ${attr}="${set}">`);
  }
  return problems;
}

/** CSS only: .css files, <style> blocks and style attributes — not prose or code samples that mention a URL. */
function cssOf(file: string): string {
  const text = readFileSync(file, 'utf8');
  if (file.endsWith('.css')) return text;
  const blocks = [...text.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => present(m[1], 'the style block'));
  return [...blocks, ...tags(text).flatMap((t) => (t.attrs.style === undefined ? [] : [t.attrs.style]))].join('\n');
}

/** Every `@import` or `url()` in one file's CSS (or the CSS it holds) that names a network URL. */
function cssRemoteProblems(file: string): string[] {
  const problems: string[] = [];
  const text = cssOf(file);
  for (const m of text.matchAll(/@import\s+(?:url\(\s*)?["']?((?:https?:)?\/\/[^"')\s;]+)/gi))
    problems.push(`${name(file)}: @import ${present(m[1], 'the @import URL')}`);
  for (const m of text.matchAll(/url\(\s*["']?((?:https?:)?\/\/[^"')\s]+)/gi))
    problems.push(`${name(file)}: url(${present(m[1], 'the url() URL')})`);
  return problems;
}

/**
 * Every code point in `text` that is invisible or changes text direction: a C0 control (0x00–0x1f), a C1 control
 * (0x7f–0x9f), one of `extra`'s closed ranges, or Unicode category Cf (bidirectional controls, zero-width
 * characters, the byte order mark) — except the code points in `allowed` (tab, newline, and carriage return where
 * the caller allows it). Read by code point, not a regex with the control characters spelled as `\x`/`\u` escapes:
 * eslint's no-control-regex is for an accidental one; here they are the deliberate subject of the test, so they are
 * data, not routed around a real finding.
 */
function hiddenCodePoints(
  text: string,
  allowed: ReadonlySet<number>,
  extra: readonly (readonly [number, number])[],
): number[] {
  const formatChar = /\p{Cf}/u;
  const found: number[] = [];
  for (let i = 0; i < text.length; i++) {
    // Printable ASCII, nearly every character of the tree, needs no check: read by UTF-16 unit, so the whole-tree scan
    // stays inside its test's time under coverage (the code review's round 3 on demo-scene-refresh, R3-RELIABILITY-002).
    const unit = text.charCodeAt(i);
    if (unit >= 0x20 && unit < 0x7f) continue;
    const cp = present(text.codePointAt(i), 'a character with no code point');
    if (cp > 0xffff) i++;
    if (allowed.has(cp)) continue;
    const isC0 = cp <= 0x1f;
    const isC1 = cp >= 0x7f && cp <= 0x9f;
    const isExtra = extra.some(([from, to]) => cp >= from && cp <= to);
    if (isC0 || isC1 || isExtra || formatChar.test(String.fromCodePoint(cp))) found.push(cp);
  }
  return found;
}

