/** A page's Watch it run section: its video's src, and its line's commit, date and models; or what is missing. */
type WatchSection =
  | {
      readonly ok: true;
      readonly src: string;
      readonly commit: string;
      readonly date: string;
      readonly models: string[];
    }
  | { readonly ok: false; readonly error: string };

function watchSection(markdown: string): WatchSection {
  const at = markdown.indexOf('\n## Watch it run');
  if (at === -1) return { ok: false, error: 'no "## Watch it run" section' };
  const section = present(markdown.slice(at + 1).split(/\n## /)[0], 'the Watch it run section');
  const video = /<video controls preload="metadata" src="([^"]+)"><\/video>/.exec(section);
  if (video === null)
    return { ok: false, error: 'no <video controls preload="metadata" src="…"></video> in its section' };
  const line = /Recorded at `([0-9a-f]{7,40})` on (\d{4}-\d{2}-\d{2}), its team on (.+?) \(\[sidecar\]/.exec(section);
  if (line === null)
    return {
      ok: false,
      error: 'no "Recorded at `<commit>` on <date>, its team on <models> ([sidecar]…" line in its section',
    };
  const models = [...present(line[3], 'the models group').matchAll(/`([^`]+)`/g)]
    .map((m) => present(m[1], 'the model name group'))
    .sort(byCodeUnit);
  return {
    ok: true,
    src: present(video[1], 'the video src group'),
    commit: present(line[1], 'the commit group'),
    date: present(line[2], 'the date group'),
    models,
  };
}

/** One demo's video and sidecar: missing or git-ignored, sha256, frame size, the commit's ancestry, and today's models. */
function videoSidecarProblems(demo: DemoEntry): string[] {
  const problems: string[] = [];
  const slug = slugOf(demo);
  const video = join(VIDEOS, `${slug}.webm`);
  const sidecarFile = join(VIDEOS, `${slug}.json`);
  for (const file of [video, sidecarFile]) {
    if (!existsSync(file)) problems.push(`${name(file)}: missing`);
    else if (spawnSync('git', ['check-ignore', '--quiet', file], { cwd: ROOT }).status === 0)
      problems.push(`${name(file)}: ignored by git`);
  }
  if (!existsSync(video) || !existsSync(sidecarFile)) return problems;
  const sidecar = JSON.parse(readFileSync(sidecarFile, 'utf8')) as Sidecar;
  if (sha256Of(video) !== sidecar.sha256) problems.push(`${name(video)}: sha256 differs from its sidecar's`);
  if (sidecar.frameSize.width !== 2560 || sidecar.frameSize.height !== 1440)
    problems.push(
      `${name(sidecarFile)}: frame ${String(sidecar.frameSize.width)} × ${String(sidecar.frameSize.height)}, not 2560 × 1440`,
    );
  // That its commit is an ancestor of HEAD is videos-history.test.ts's: the commit is internal history, which a
  // published clone does not hold (docs/plans/oss-release.md R2, R12).
  if (!/^[0-9a-f]{40}$/.test(sidecar.commit)) problems.push(`${name(sidecarFile)}: its commit is no commit id`);
  const today = teamModels(demo.team);
  if ([...sidecar.models].sort(byCodeUnit).join(',') !== today.join(','))
    problems.push(
      `${name(sidecarFile)}: models ${sidecar.models.join(', ')}, its team's recipes name ${today.join(', ')}`,
    );
  return problems;
}

