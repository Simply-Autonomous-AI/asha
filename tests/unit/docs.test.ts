/**
 * The absolute paths among `paths` that git ignores, by one `git check-ignore`: exit 0 lists the ignored ones, 1 means
 * none is, anything else throws. A tracked file is never listed, whatever the ignore rules say.
 */
function ignoredByGit(paths: readonly string[]): Set<string> {
  const check = spawnSync('git', ['check-ignore', '--stdin'], { cwd: ROOT, input: paths.join('\n'), encoding: 'utf8' });
  if (check.status !== 0 && check.status !== 1)
    throw new Error(`git check-ignore exited ${String(check.status)}: ${check.stderr}`);
  return new Set(
    check.stdout
      .split('\n')
      .filter((line) => line !== '')
      .map((file) => resolve(ROOT, file)),
  );
}

interface Tag {
  readonly tag: string;
  readonly attrs: Readonly<Record<string, string>>;
}

const TAG_OPEN = /<([a-zA-Z][\w:-]*)/;
const ATTR_NAME = /^\s+([^\s=>/]+)/;
const ATTR_VALUE = /^\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/;
const TAG_CLOSE = /^\s*\/?>/;

/**
 * Every real tag in a page with its attributes. Script and style bodies and
 * comments are dropped first, and escaped markup in code samples (&lt;a href…)
 * is text, not a tag, so neither is mistaken for a link. Matched a piece at a
 * time (TAG_OPEN, then each attribute, then TAG_CLOSE) rather than with one
 * regex, so every pattern stays under sonarjs/regex-complexity's limit; a
 * quoted value may hold `>`, `<` or the other quote without ending the tag
 * early, and one right before a `/>` with no space is still read correctly —
 * checked byte-for-byte against every page under docs/ and a battery of
 * crafted tags when this was written.
 */
function tags(html: string): Tag[] {
  const markup = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/(<script\b[^>]*>)[\s\S]*?<\/script>/gi, '$1')
    .replace(/(<style\b[^>]*>)[\s\S]*?<\/style>/gi, '$1');
  const out: Tag[] = [];
  let pos = 0;
  for (;;) {
    const open = TAG_OPEN.exec(markup.slice(pos));
    if (open === null) break;
    let cursor = pos + open.index + open[0].length;
    const attrs: [string, string][] = [];
    for (;;) {
      const nameMatch = ATTR_NAME.exec(markup.slice(cursor));
      if (nameMatch === null) break;
      cursor += nameMatch[0].length;
      const attrName = present(nameMatch[1], 'the attribute name').toLowerCase();
      const valueMatch = ATTR_VALUE.exec(markup.slice(cursor));
      let value = '';
      if (valueMatch !== null) {
        value = (valueMatch[1] ?? valueMatch[2] ?? valueMatch[3] ?? '').replace(/&amp;/g, '&');
        cursor += valueMatch[0].length;
      }
      attrs.push([attrName, value]);
    }
    const close = TAG_CLOSE.exec(markup.slice(cursor));
    if (close === null) {
      pos += open.index + 1;
      continue;
    }
    out.push({ tag: present(open[1], 'the tag name').toLowerCase(), attrs: Object.fromEntries(attrs) });
    pos = cursor + close[0].length;
  }
  return out;
}

/** Every href and src in a page, as written. */
function links(page: string): string[] {
  return tags(readFileSync(page, 'utf8')).flatMap((t) =>
    [t.attrs.href, t.attrs.src].filter((v): v is string => v !== undefined),
  );
}

const isNetwork = (url: string): boolean => /^(https?:)?\/\//i.test(url.trim());
